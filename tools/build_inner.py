"""Builds the v2 inner pages (providers, primer, compare, software) from the original site.

Run from the site root (the folder that holds index.html and v2/):
    python v2/tools/build_inner.py [--pages]   # --pages also regenerates the HTML pages (overwrites hand edits)

Always writes v2/assets/inner.css (the original stylesheet re-themed + tools/inner-shell.css).
"""
import re, shutil, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
V2 = ROOT / "v2"

PROVIDERS = [
    # slug, name, flagship, logo, camp
    ("nvidia", "Nvidia", "Vera Rubin NVL72", "nvidia.svg", "gpu"),
    ("amd", "AMD", "MI455X · Helios", "amd.svg", "gpu"),
    ("google-tpu", "Google TPU", "TPU 8t · 8i · 8tx", "google-icon.svg", "asic"),
    ("aws", "AWS", "Trainium3", "aws.svg", "asic"),
    ("microsoft-maia", "Microsoft", "Maia 300", "microsoft-icon.svg", "asic"),
    ("qualcomm", "Qualcomm", "Dragonfly AI250", "qualcomm.svg", "spec"),
    ("cerebras", "Cerebras", "WSE-3 Turbo · CS-4", "cerebras.svg", "spec"),
    ("groq", "Groq", "LPU · Groq 3", "groq.svg", "spec"),
]
GUIDE = [("index.html", "Home"), ("primer.html", "Primer"), ("compare.html", "Compare"), ("software.html", "Software")]

CUR = ' aria-current="page"'

NEW_ROOT = """:root {
  --bg: #111111; --bg-glow: transparent;
  --surface: #1c1c1c; --surface-2: #262626;
  --text: #f2f2f2; --muted: #a3a3a3; --border: #303030;
  --accent: #a08672; --accent-2: #a08672; --link: #c9ad98;
  --grad: linear-gradient(#a08672, #a08672);
  --camp-gpu: #3fae6a; --camp-asic: #4d8fe6; --camp-spec: #e8803a;
  --r-gpu: #3fae6a; --r-cpu: #4d8fe6; --r-net: #2fa7b8; --r-dpu: #e8803a; --r-power: #e5605f; --r-tray: #7b8794;
  --vendor: #7c8496; --verify: #d48a12;
  --radius: 14px;
  --shadow: none; --shadow-hover: none;
  --max: 1120px;
  --font: "Reddit Sans", system-ui, -apple-system, "Segoe UI", sans-serif;
  --display: "Reddit Sans", system-ui, sans-serif;
  --mono: "JetBrains Mono", ui-monospace, Consolas, monospace;
  color-scheme: dark;
}
"""


def build_css():
    css = (ROOT / "assets/css/style.css").read_text(encoding="utf-8")
    start = css.index("* { box-sizing: border-box; }")
    body = css[start:]
    out = "/* v2 inner pages: the original stylesheet, re-themed. Generated by tools/build_inner.py; edit tools/inner-shell.css or the script, not this file. */\n"
    out += NEW_ROOT + body + (V2 / "tools/inner-shell.css").read_text(encoding="utf-8")
    (V2 / "assets/inner.css").write_text(out, encoding="utf-8")


# the provider bar's three groups, named as the home page's camps and the Racks menu name them
CAMPS = [("gpu", "Merchant GPUs"), ("asic", "Hyperscaler ASICs"), ("spec", "Specialists")]


def sidebar(rel, current):
    """The provider bar: only the eight racks, in their three camps. The guide's pages live in the header,
    so the bar repeats none of them."""
    def plink(slug, name, flag, logo, camp):
        cur = CUR if current == f"providers/{slug}.html" else ""
        return (f'<a class="side__p" href="{rel}providers/{slug}.html"{cur}>'
                f'<span class="side__logo"><img src="{rel}assets/icons/{logo}" alt=""></span><b>{name}</b><span>{flag}</span></a>')
    groups = []
    for camp, label in CAMPS:
        members = [p for p in PROVIDERS if p[4] == camp]
        links = "\n        ".join(plink(*p) for p in members)
        groups.append(f"""<div class="side__group" data-camp="{camp}">
        <p class="side__h"><i class="side__dot" aria-hidden="true"></i>{label} <small>{len(members)}</small></p>
        {links}
      </div>""")
    body = "\n      ".join(groups)
    return f"""<nav class="side" aria-label="Providers">
      {body}
    </nav>"""


def header(rel, current):
    links = "".join(
        f'<a href="{rel}{href}"{CUR if current == href else ""}>{label}</a>' for href, label in GUIDE)
    return f"""<header class="top">
    <div class="top__bar">
      <a class="skip" href="#main">Skip to content</a>
      <a class="top__logo" href="{rel}index.html"><svg viewBox="0 0 24 24" aria-hidden="true"><path d="M2.5 21.5V12a9.5 9.5 0 0 1 19 0v9.5h-6V12a3.5 3.5 0 0 0-7 0v9.5z"/></svg>AI Accelerators 101</a>
      <nav class="top__links" aria-label="Main">{links}</nav>
      <a class="btn top__cta" href="{rel}index.html#racks">See all eight racks</a>
    </div>
  </header>

  {sidebar(rel, current)}"""


HEAD_LINKS = """<link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link href="https://fonts.googleapis.com/css2?family=Reddit+Sans:wght@400..700&family=JetBrains+Mono:wght@400..500&display=swap" rel="stylesheet">
  <link rel="icon" href="{rel}favicon.svg" type="image/svg+xml">
  <meta name="theme-color" content="#111111">
  <link rel="stylesheet" href="{rel}assets/inner.css">
  <link rel="stylesheet" href="{rel}assets/side.css">"""


def build_page(src_rel):
    rel = "../" if src_rel.startswith("providers/") else ""
    html = (ROOT / src_rel).read_text(encoding="utf-8")
    html = re.sub(r'<link rel="stylesheet" href="[^"]*assets/css/style\.css">', HEAD_LINKS.format(rel=rel), html, count=1)
    html = re.sub(r'<header class="site-header">.*?</header>', lambda m: header(rel, src_rel), html, count=1, flags=re.S)
    html = html.replace("<body>", '<body class="has-side">', 1)
    html = html.replace('<main class="wrap">', '<main class="wrap" id="main">', 1)
    legal = ('<p class="site-footer__legal">AI Accelerators 101 · Figures as of 12 November 2026 · Vendor claims are labelled as such. '
             'Product names and logos are trademarks of their owners.</p>')
    html = re.sub(r'(<footer class="site-footer">\s*<div class="wrap">)(.*?)(</div>\s*</footer>)',
                  lambda m: m.group(1) + m.group(2).rstrip() + "\n      " + legal + "\n    " + m.group(3), html, count=1, flags=re.S)
    html = re.sub(r'(<footer class="site-footer">\s*<div class="wrap">)\s*All AI Accelerators 101[^<]*', r'', html, count=1)
    dst = V2 / src_rel
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(html, encoding="utf-8")


def main():
    (V2 / "assets/js").mkdir(parents=True, exist_ok=True)
    for js in (ROOT / "assets/js").glob("*.js"):
        shutil.copy(js, V2 / "assets/js" / js.name)
    build_css()
    if "--pages" in sys.argv:
        for p in [f"providers/{s[0]}.html" for s in PROVIDERS] + ["primer.html", "compare.html", "software.html"]:
            build_page(p)
            print("built", p)
    # the sidebar fragment for index.html (pasted by hand once)
    (V2 / "tools/sidebar-index.html").write_text(sidebar("", "index.html"), encoding="utf-8")
    print("wrote assets/inner.css")


if __name__ == "__main__":
    main()
